#!/usr/bin/env bash
# Deploy the shop AI assistant to STAGING (shared staging k3s VPS, namespace shop-ai-staging, https://ai.square.al).
#
#   k8s/deploy-staging.sh                  # build, push (app + OpenWA), update secret, apply, roll out
#   k8s/deploy-staging.sh --skip-openwa    # same, but do not build/push the OpenWA image (big, rarely changes);
#                                          # it must already be in the VPS registry (checked)
#   k8s/deploy-staging.sh --dry-run        # print the steps only (no docker, no ssh, no secret values)
#
# Needs: docker, git, ssh, curl; env STAGING_SSH_USER, STAGING_SSH_HOST, STAGING_SSH_KEY;
#        k8s/.env.staging (gitignored, template k8s/staging.env.example).
#
# The app image is built from the committed HEAD (git archive), never from uncommitted files, so the tag
# <date>-<time>-<gitsha>-stg always matches a commit. Commit first.
# The OpenWA image has a FIXED tag = the pinned OpenWA commit (ARG OPENWA_REF in docker/openwa/Dockerfile, short),
# so app deploys never restart the gateway. If you change docker/openwa/ (patches) without bumping OPENWA_REF,
# set OPENWA_TAG=<new tag> in the environment. A local image shop-ai/openwa:<tag> (docker compose build) is reused
# instead of rebuilding (~1.1 GB).
#
# OpenWA API key: generated by the gateway on its first boot. First deploy runs with OPENWA_API_KEY empty; the
# script then prints the one-time command to read it. Put it in k8s/.env.staging and re-run with --skip-openwa.
#
# The VPS is shared and its disk is tight: this script never prunes docker or registry images there.
# Old tags stay in the VPS registry until someone removes them deliberately.
set -euo pipefail

NAMESPACE=shop-ai-staging
SECRET=shop-ai-env
IMAGE_NAME=shop-ai/app
OPENWA_IMAGE_NAME=shop-ai/openwa
REMOTE_REGISTRY=localhost:5000   # what the k3s node pulls from
TUNNEL_PORT=5004                 # local end of the ssh tunnel to the VPS registry
PUBLIC_URL=https://ai.square.al
OPENWA_URL_EXPECTED=http://openwa:2785

DRY_RUN=0
SKIP_OPENWA=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --skip-openwa) SKIP_OPENWA=1 ;;
    -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d'; exit 0 ;;
    *) echo "unknown argument: $arg (use --dry-run, --skip-openwa or --help)" >&2; exit 2 ;;
  esac
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
ENV_FILE="$ROOT/k8s/.env.staging"
MANIFEST="$ROOT/k8s/staging.yaml"

die() { echo "error: $*" >&2; exit 1; }
step() { echo; echo "==> $*"; }
# env_value KEY: value of KEY= in the env file ("" when absent/empty).
env_value() { grep -E "^$1=" "$ENV_FILE" | tail -n1 | cut -d= -f2- || true; }

# ─── Preflight (before any docker/ssh call) ──────────────────────────────────
OPENWA_KEY_SET=0
if [[ ! -f "$ENV_FILE" ]]; then
  if (( DRY_RUN )); then
    echo "WARNING: $ENV_FILE is missing: a real run would refuse here (cp k8s/staging.env.example k8s/.env.staging)."
  else
    die "$ENV_FILE is missing. cp k8s/staging.env.example k8s/.env.staging and fill it in. Refusing to deploy."
  fi
else
  # Required keys must be present and non-empty; quoted values would be stored with the quotes.
  for key in POSTGRES_USER POSTGRES_PASSWORD POSTGRES_DB DATABASE_URL BETTER_AUTH_SECRET BETTER_AUTH_URL \
             ENCRYPTION_KEY OPENWA_URL OPENWA_WEBHOOK_SECRET OPENWA_WEBHOOK_URL; do
    grep -Eq "^${key}=.+" "$ENV_FILE" || die "$key is missing or empty in $ENV_FILE"
  done
  if grep -Eq '^[A-Z_]+=["'\'']' "$ENV_FILE"; then
    die "$ENV_FILE has quoted values; kubectl keeps quotes literally. Remove them."
  fi
  grep -Eq "^BETTER_AUTH_URL=${PUBLIC_URL}/?$" "$ENV_FILE" || die "BETTER_AUTH_URL must be ${PUBLIC_URL}"
  grep -Eq '^ENCRYPTION_KEY=[0-9a-fA-F]{64}$' "$ENV_FILE" || die "ENCRYPTION_KEY must be 64 hex chars (32 bytes)"
  [[ "$(env_value OPENWA_URL)" == "$OPENWA_URL_EXPECTED" ]] || die "OPENWA_URL must be ${OPENWA_URL_EXPECTED} (in-cluster service)"
  # The gateway validates webhook URLs with @IsUrl(): a single-label host (http://app/...) is rejected, and the
  # app's registration only logs the failure, so inbound WhatsApp would silently never arrive.
  WEBHOOK_URL="$(env_value OPENWA_WEBHOOK_URL)"
  [[ "$WEBHOOK_URL" =~ ^https?://[^/:]+\.[^/:]+(:[0-9]+)?/api/webhooks/openwa$ ]] \
    || die "OPENWA_WEBHOOK_URL must use a dotted host, e.g. http://app.${NAMESPACE}.svc.cluster.local/api/webhooks/openwa (got: ${WEBHOOK_URL})"
  [[ -n "$(env_value OPENWA_API_KEY)" ]] && OPENWA_KEY_SET=1
fi

if (( DRY_RUN )); then
  SSH_USER="${STAGING_SSH_USER:-\$STAGING_SSH_USER}"
  SSH_HOST="${STAGING_SSH_HOST:-\$STAGING_SSH_HOST}"
  SSH_KEY="${STAGING_SSH_KEY:-\$STAGING_SSH_KEY}"
else
  SSH_USER="${STAGING_SSH_USER:?set STAGING_SSH_USER}"
  SSH_HOST="${STAGING_SSH_HOST:?set STAGING_SSH_HOST}"
  SSH_KEY="${STAGING_SSH_KEY:?set STAGING_SSH_KEY}"
  [[ -r "$SSH_KEY" ]] || die "STAGING_SSH_KEY ($SSH_KEY) is not readable"
  for bin in docker git ssh curl; do command -v "$bin" >/dev/null || die "$bin not found"; done
fi

SHA="$(git rev-parse --short HEAD)"
TAG="$(date +%Y%m%d-%H%M%S)-${SHA}-stg"
REMOTE_IMAGE="${REMOTE_REGISTRY}/${IMAGE_NAME}:${TAG}"
PUSH_IMAGE="localhost:${TUNNEL_PORT}/${IMAGE_NAME}:${TAG}"

OPENWA_REF="$(sed -nE 's/^ARG OPENWA_REF=([0-9a-fA-F]{7,40})$/\1/p' docker/openwa/Dockerfile | head -n1)"
[[ -n "$OPENWA_REF" ]] || die "could not read ARG OPENWA_REF from docker/openwa/Dockerfile"
OPENWA_TAG="${OPENWA_TAG:-${OPENWA_REF:0:7}}"
[[ "$OPENWA_TAG" =~ ^[A-Za-z0-9_.-]{1,64}$ ]] || die "invalid OPENWA_TAG: $OPENWA_TAG"
OPENWA_LOCAL_IMAGE="${OPENWA_IMAGE_NAME}:${OPENWA_TAG}"   # what `docker compose build openwa` produces
OPENWA_REMOTE_IMAGE="${REMOTE_REGISTRY}/${OPENWA_IMAGE_NAME}:${OPENWA_TAG}"
OPENWA_PUSH_IMAGE="localhost:${TUNNEL_PORT}/${OPENWA_IMAGE_NAME}:${OPENWA_TAG}"

SSH_OPTS=(-i "$SSH_KEY" -o BatchMode=yes -o ConnectTimeout=15)
SSH_TARGET="${SSH_USER}@${SSH_HOST}"
RENDER="sed -e 's/__IMAGE_TAG__/${TAG}/' -e 's/__OPENWA_TAG__/${OPENWA_TAG}/' k8s/staging.yaml"
KEY_CMD="ssh -i ${SSH_KEY} ${SSH_TARGET} sudo -n kubectl -n ${NAMESPACE} exec openwa-0 -- cat /app/data/.api-key"

if [[ -n "$(git status --porcelain --untracked-files=no)" ]]; then
  echo "NOTE: the working tree has uncommitted changes; they are NOT in the image (built from HEAD ${SHA})."
fi

# remote "<kubectl args>": runs sudo -n kubectl on the VPS (stdin is forwarded).
remote() { ssh "${SSH_OPTS[@]}" "$SSH_TARGET" "$@"; }

if (( DRY_RUN )); then
  if (( SKIP_OPENWA )); then
    OPENWA_BUILD="1b. openwa  SKIPPED (--skip-openwa)"
    OPENWA_PUSH="3b. check  curl -sfI http://localhost:${TUNNEL_PORT}/v2/${OPENWA_IMAGE_NAME}/manifests/${OPENWA_TAG}
           (refuses to deploy when ${OPENWA_REMOTE_IMAGE} is not in the VPS registry yet)"
  else
    if [[ "$(docker image inspect "$OPENWA_LOCAL_IMAGE" --format '{{.Os}}/{{.Architecture}}' 2>/dev/null || true)" == "linux/amd64" ]]; then
      OPENWA_BUILD="1b. openwa  docker tag ${OPENWA_LOCAL_IMAGE} ${OPENWA_PUSH_IMAGE}   (local linux/amd64 image found: no rebuild)"
    else
      OPENWA_BUILD="1b. openwa  git archive --format=tar HEAD:docker/openwa | docker build --platform linux/amd64 \\
             -t ${OPENWA_LOCAL_IMAGE} -t ${OPENWA_PUSH_IMAGE} -   (no local ${OPENWA_LOCAL_IMAGE}: full build)"
    fi
    OPENWA_PUSH="3b. push   docker push ${OPENWA_PUSH_IMAGE}   (~1.1 GB uncompressed on first push; later pushes skip existing layers)"
  fi
  cat <<EOF

DRY RUN: nothing is built, pushed or applied. Steps a real run would perform:

1. build   git archive --format=tar HEAD | docker build --platform linux/amd64 \\
             -t ${REMOTE_IMAGE} -t ${PUSH_IMAGE} -
${OPENWA_BUILD}
2. tunnel  ssh ${SSH_OPTS[*]} -o ExitOnForwardFailure=yes -N -L ${TUNNEL_PORT}:127.0.0.1:5000 ${SSH_TARGET} &
           (wait for http://localhost:${TUNNEL_PORT}/v2/, closed again on exit)
3. push    docker push ${PUSH_IMAGE}
${OPENWA_PUSH}
4. ns      ssh ${SSH_TARGET} sudo -n kubectl create namespace ${NAMESPACE} --dry-run=client -o yaml | sudo -n kubectl apply -f -
5. secret  ssh ${SSH_TARGET} "cat | sudo -n kubectl -n ${NAMESPACE} create secret generic ${SECRET} --from-env-file=/dev/stdin \\
             --dry-run=client -o yaml | sudo -n kubectl apply -f -" < k8s/.env.staging
           (values travel over ssh stdin only; nothing is written to the VPS disk)
6. apply   ${RENDER} | ssh ${SSH_TARGET} sudo -n kubectl apply -f -
7. db      ssh ${SSH_TARGET} sudo -n kubectl -n ${NAMESPACE} rollout status statefulset/postgres --timeout=180s
8. openwa  ssh ${SSH_TARGET} sudo -n kubectl -n ${NAMESPACE} rollout status statefulset/openwa --timeout=300s  (warning only)
9. image   ssh ${SSH_TARGET} sudo -n kubectl -n ${NAMESPACE} set image deployment/app app=${REMOTE_IMAGE}
10. wait   ssh ${SSH_TARGET} sudo -n kubectl -n ${NAMESPACE} rollout status deployment/app --timeout=300s
11. check  ssh ${SSH_TARGET} sudo -n kubectl -n ${NAMESPACE} get pods,ingress,certificate
           then ${PUBLIC_URL}/login
12. key    OPENWA_API_KEY $( (( OPENWA_KEY_SET )) && echo "is set in k8s/.env.staging: compared (by sha256, on the VPS) with the gateway's /app/data/.api-key" || echo "is EMPTY: the script prints the one-time step:
             ${KEY_CMD}
           -> paste into k8s/.env.staging as OPENWA_API_KEY, then k8s/deploy-staging.sh --skip-openwa")
EOF
  exit 0
fi

# ─── 1. Build ─────────────────────────────────────────────────────────────────
step "build ${REMOTE_IMAGE} from HEAD ${SHA}"
git archive --format=tar HEAD | docker build --platform linux/amd64 -t "$REMOTE_IMAGE" -t "$PUSH_IMAGE" -

if (( ! SKIP_OPENWA )); then
  if [[ "$(docker image inspect "$OPENWA_LOCAL_IMAGE" --format '{{.Os}}/{{.Architecture}}' 2>/dev/null || true)" == "linux/amd64" ]]; then
    step "openwa: reuse local ${OPENWA_LOCAL_IMAGE} (no rebuild)"
    docker tag "$OPENWA_LOCAL_IMAGE" "$OPENWA_PUSH_IMAGE"
  else
    step "openwa: build ${OPENWA_LOCAL_IMAGE} from HEAD:docker/openwa (big: Chromium)"
    git archive --format=tar "HEAD:docker/openwa" \
      | docker build --platform linux/amd64 -t "$OPENWA_LOCAL_IMAGE" -t "$OPENWA_PUSH_IMAGE" -
  fi
fi

# ─── 2-3. Tunnel + push ───────────────────────────────────────────────────────
step "open ssh tunnel localhost:${TUNNEL_PORT} -> ${SSH_HOST}:5000"
ssh "${SSH_OPTS[@]}" -o ExitOnForwardFailure=yes -N -L "${TUNNEL_PORT}:127.0.0.1:5000" "$SSH_TARGET" &
TUNNEL_PID=$!
trap 'kill "$TUNNEL_PID" 2>/dev/null || true' EXIT
for _ in $(seq 1 30); do
  curl -sf "http://localhost:${TUNNEL_PORT}/v2/" >/dev/null && break
  kill -0 "$TUNNEL_PID" 2>/dev/null || die "ssh tunnel exited (port ${TUNNEL_PORT} busy?)"
  sleep 1
done
curl -sf "http://localhost:${TUNNEL_PORT}/v2/" >/dev/null || die "registry not reachable through the tunnel"

step "push ${PUSH_IMAGE}"
docker push "$PUSH_IMAGE"

if (( SKIP_OPENWA )); then
  step "openwa: --skip-openwa, checking ${OPENWA_REMOTE_IMAGE} is in the registry"
  curl -sfI -o /dev/null \
    -H 'Accept: application/vnd.oci.image.index.v1+json, application/vnd.oci.image.manifest.v1+json, application/vnd.docker.distribution.manifest.list.v2+json, application/vnd.docker.distribution.manifest.v2+json' \
    "http://localhost:${TUNNEL_PORT}/v2/${OPENWA_IMAGE_NAME}/manifests/${OPENWA_TAG}" \
    || die "${OPENWA_REMOTE_IMAGE} is not in the VPS registry yet: run once without --skip-openwa"
else
  step "push ${OPENWA_PUSH_IMAGE} (first push is large; later ones skip existing layers)"
  docker push "$OPENWA_PUSH_IMAGE"
fi
kill "$TUNNEL_PID" 2>/dev/null || true

# ─── 4-5. Namespace + Secret ──────────────────────────────────────────────────
step "namespace ${NAMESPACE}"
remote "sudo -n kubectl create namespace ${NAMESPACE} --dry-run=client -o yaml | sudo -n kubectl apply -f -"

step "secret ${SECRET} from k8s/.env.staging (via ssh stdin)"
# `cat |` makes kubectl's stdin a pipe: sshd may hand the remote command a socket, which /dev/stdin cannot open.
remote "cat | sudo -n kubectl -n ${NAMESPACE} create secret generic ${SECRET} --from-env-file=/dev/stdin \
  --dry-run=client -o yaml | sudo -n kubectl apply -f -" < "$ENV_FILE"

# ─── 6-10. Manifest, postgres, openwa, image, rollout ─────────────────────────
step "apply k8s/staging.yaml (app ${TAG}, openwa ${OPENWA_TAG})"
sed -e "s/__IMAGE_TAG__/${TAG}/" -e "s/__OPENWA_TAG__/${OPENWA_TAG}/" "$MANIFEST" | remote "sudo -n kubectl apply -f -"

step "wait for postgres"
remote "sudo -n kubectl -n ${NAMESPACE} rollout status statefulset/postgres --timeout=180s"

step "wait for openwa (a failure here does not block the app)"
OPENWA_UP=1
if ! remote "sudo -n kubectl -n ${NAMESPACE} rollout status statefulset/openwa --timeout=300s"; then
  OPENWA_UP=0
  echo "WARNING: openwa is not ready; last logs:" >&2
  remote "sudo -n kubectl -n ${NAMESPACE} logs statefulset/openwa --tail=60" >&2 || true
fi

step "set image ${REMOTE_IMAGE}"
remote "sudo -n kubectl -n ${NAMESPACE} set image deployment/app app=${REMOTE_IMAGE}"

step "wait for the app rollout (entrypoint runs prisma migrate deploy first)"
if ! remote "sudo -n kubectl -n ${NAMESPACE} rollout status deployment/app --timeout=300s"; then
  echo "rollout did not finish; last app logs:" >&2
  remote "sudo -n kubectl -n ${NAMESPACE} logs deployment/app --tail=80" >&2 || true
  exit 1
fi

step "status"
remote "sudo -n kubectl -n ${NAMESPACE} get pods,ingress,certificate -o wide"
echo
echo "Deployed ${REMOTE_IMAGE} (+ ${OPENWA_REMOTE_IMAGE}) -> ${PUBLIC_URL}"

# ─── 12. OpenWA API key (generated by the gateway; cannot be preset) ─────────
if (( OPENWA_UP )); then
  if (( OPENWA_KEY_SET )); then
    # Compare hashes on the VPS side only, so the key never crosses ssh: a wiped PVC means a new key.
    remote_sum="$(remote "sudo -n kubectl -n ${NAMESPACE} exec openwa-0 -- cat /app/data/.api-key | tr -d '[:space:]' | sha256sum" | cut -d' ' -f1 || true)"
    local_sum="$(env_value OPENWA_API_KEY | tr -d '[:space:]' | sha256sum | cut -d' ' -f1)"
    if [[ -n "$remote_sum" && "$remote_sum" != "$local_sum" ]]; then
      echo
      echo "WARNING: OPENWA_API_KEY in k8s/.env.staging does not match the gateway's key (PVC recreated?). Update it:"
      echo "  ${KEY_CMD}"
      echo "then: k8s/deploy-staging.sh --skip-openwa"
    fi
  else
    cat <<EOF

ONE-TIME STEP: OPENWA_API_KEY is empty, so the app cannot talk to the gateway yet. Read the key the gateway generated:
  ${KEY_CMD}
put it into k8s/.env.staging as OPENWA_API_KEY=<value> (no quotes) and re-run:
  k8s/deploy-staging.sh --skip-openwa
Then open ${PUBLIC_URL}/channels -> Shto kanal -> Lidh WhatsApp (OpenWA) and scan the QR with the DEDICATED staging number.
EOF
  fi
fi
